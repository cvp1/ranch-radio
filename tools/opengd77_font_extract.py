#!/usr/bin/env python3
"""Make opengd77_font.py from OpenGD77's HX8353E_charset.h (the MD-UV380 build).

    tools/opengd77_font_extract.py path/to/HX8353E_charset.h > opengd77_font.py

The fonts the radio draws its screen with: font_6x8, font_6x8_bold, font_8x8,
font_8x16 (FONT_SIZE_1, 1_BOLD, 2, 3 in HX8353E_display.c). Each glyph is
column-major: byte x + (y // 8) * width, bit y % 8, foreground pixels only.
Only the uncompressed fonts; font_16x32 (FONT_SIZE_4) is the compressed one
and is left out. Reads text, runs nothing from the header.
"""
import re
import sys

NAMES = ("font_6x8", "font_6x8_bold", "font_8x8", "font_8x16")


def parse(text, name):
    m = re.search(r"const\s+uint8_t\s+%s\[\]\s*=\s*\{(.*?)\};" % re.escape(name), text, re.S)
    if not m:
        raise SystemExit(f"{name} not found")
    body = re.sub(r"//[^\n]*", "", m.group(1))
    vals = [int(v, 0) for v in re.findall(r"0x[0-9a-fA-F]+|\b\d+\b", body)]
    first, last, w, h, per = vals[2], vals[3], vals[4], vals[5], vals[7]
    data = vals[8:]
    glyphs = {}
    for code in range(first, last + 1):
        g = data[(code - first) * per:(code - first + 1) * per]
        if len(g) == per:
            glyphs[code] = bytes(g)
    return w, h, glyphs


def main(path):
    text = open(path, encoding="latin-1").read()
    head = text.split("*/", 1)[0] + "*/"
    out = ['"""Screen fonts of OpenGD77 (MD-UV380 build), from HX8353E_charset.h.',
           "", "Generated by tools/opengd77_font_extract.py. The header's notice:", ""]
    out += [l.replace('"""', "'''") for l in head.splitlines()]
    out += ['"""', "", "FONTS = {"]
    for n in NAMES:
        w, h, glyphs = parse(text, n)
        out.append(f"    {n!r}: ({w}, {h}, {{")
        for code, g in glyphs.items():
            out.append(f"        {code}: bytes.fromhex({g.hex()!r}),")
        out.append("    }),")
    out.append("}")
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
